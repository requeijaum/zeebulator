TEST(Gif, ReordersInterlacedRows) {
  // Imagem 1x8 com o bit de interlace ligado: as linhas chegam na ordem
  // 0,4,2,6,1,3,5,7 e a linha final r tem que ficar com o indice r%4.
  auto decoded = DecodeGif(kInterlacedGif, sizeof(kInterlacedGif));
  ASSERT_TRUE(decoded.has_value());
  ASSERT_EQ(decoded->frames.size(), 1u);
  const auto& px = decoded->frames[0].rgba;
  ASSERT_EQ(px.size(), 8u * 4u);
  const uint8_t expected[4][3] = {{255, 0, 0}, {0, 255, 0}, {0, 0, 255}, {255, 255, 255}};
  for (int row = 0; row < 8; ++row) {
    const int want = row % 4;
    EXPECT_EQ(px[row * 4 + 0], expected[want][0]) << "linha " << row;
    EXPECT_EQ(px[row * 4 + 1], expected[want][1]) << "linha " << row;
    EXPECT_EQ(px[row * 4 + 2], expected[want][2]) << "linha " << row;
  }
}

