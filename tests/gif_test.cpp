TEST(Gif, DecodesPalette256WithGrowingCodeSizes) {
  // 16x16 com minimum code size 8: o fluxo LZW passa por codigos de 9
  // bits em diante, o mesmo caminho do arquivo real.
  auto decoded = DecodeGif(kPalette256Gif, sizeof(kPalette256Gif));
  ASSERT_TRUE(decoded.has_value());
  ASSERT_EQ(decoded->frames.size(), 1u);
  const auto& px = decoded->frames[0].rgba;
  ASSERT_EQ(px.size(), 16u * 16u * 4u);
  std::set<uint32_t> colors;
  for (size_t i = 0; i < px.size(); i += 4) {
    colors.insert((static_cast<uint32_t>(px[i]) << 16) | (static_cast<uint32_t>(px[i + 1]) << 8) |
                  px[i + 2]);
  }
  // Os indices sao (x*7 + y*13) % 256 numa grade 16x16: 229 indices
  // distintos, que caem em 228 cores RGB distintas nesta paleta
  // (duas entradas da paleta sao iguais). Numero medido com um
  // decodificador de referencia independente.
  EXPECT_EQ(colors.size(), 228u);
  auto pixel = [&](int x, int y) {
    const size_t o = (static_cast<size_t>(y) * 16 + x) * 4;
    return std::vector<uint8_t>(px.begin() + o, px.begin() + o + 3);
  };
  EXPECT_EQ(pixel(0, 0), (std::vector<uint8_t>{165, 77, 202}));
  EXPECT_EQ(pixel(7, 3), (std::vector<uint8_t>{88, 72, 242}));
  EXPECT_EQ(pixel(15, 15), (std::vector<uint8_t>{205, 31, 97}));
}

