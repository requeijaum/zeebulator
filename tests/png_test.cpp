TEST(Png, DecodesARealRgbaPngPixelPerfect) {
  int w = 0, h = 0;
  auto result = DecodePng(kRealPng8x8, sizeof(kRealPng8x8), w, h);
  ASSERT_TRUE(result.has_value());
  EXPECT_EQ(w, 8);
  EXPECT_EQ(h, 8);
  ASSERT_EQ(result->size(), 8u * 8u * 4u);
  for (int y = 0; y < 8; ++y) {
    for (int x = 0; x < 8; ++x) {
      SCOPED_TRACE(testing::Message() << "x=" << x << " y=" << y);
      const uint8_t* px = result->data() + (y * 8 + x) * 4;
      EXPECT_EQ(px[0], kExpectedPixels[y][x][0]);
      EXPECT_EQ(px[1], kExpectedPixels[y][x][1]);
      EXPECT_EQ(px[2], kExpectedPixels[y][x][2]);
      EXPECT_EQ(px[3], kExpectedPixels[y][x][3]);
    }
  }
}

TEST(Png, RejectsDataWithoutTheRealPngSignature) {
  const uint8_t kNotPng[8] = {0, 1, 2, 3, 4, 5, 6, 7};
  int w = 0, h = 0;
  EXPECT_FALSE(DecodePng(kNotPng, sizeof(kNotPng), w, h).has_value());
}

TEST(Png, RejectsTruncatedData) {
  int w = 0, h = 0;
  EXPECT_FALSE(DecodePng(kRealPng8x8, 16, w, h).has_value());
}

