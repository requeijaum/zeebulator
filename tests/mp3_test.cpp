TEST(Mp3, DecodesRealMp3ToPcm) {
  auto result = ParseMp3(kToneMp3, sizeof(kToneMp3));
  ASSERT_TRUE(result.has_value()) << "a valid MP3 must decode";
  EXPECT_EQ(result->channels, 1);
  EXPECT_EQ(result->sample_rate, 44100);
  EXPECT_GT(result->samples.size(), 0u) << "at least one frame of PCM";
  // A 440 Hz tone is not silence: some sample must be clearly non-zero.
  bool has_signal = false;
  for (int16_t s : result->samples) {
    if (s > 200 || s < -200) { has_signal = true; break; }
  }
  EXPECT_TRUE(has_signal) << "decoded PCM should carry the tone, not silence";
}

TEST(Mp3, RejectsNonMp3Data) {
  const uint8_t junk[] = {'n', 'o', 't', 'a', 'n', 'm', 'p', '3', 0, 0, 0, 0};
  EXPECT_FALSE(ParseMp3(junk, sizeof(junk)).has_value());
}

TEST(Mp3, RejectsEmptyAndTiny) {
  EXPECT_FALSE(ParseMp3(nullptr, 0).has_value());
  const uint8_t two[] = {0xFF, 0xFB};
  EXPECT_FALSE(ParseMp3(two, sizeof(two)).has_value());
}
